test("automation saves validate all numbers serialize writes and retain rejected drafts", async ({ page }) => {
  const fixture = await setup(page);
  await page.goto(`${WEB}/#automation`);
  await page.locator(".automation-entry-config > summary").click();
  const capital = page.getByLabel("资金 (USD)", { exact: true });
  const save = page.getByRole("button", { name: "保存门槛", exact: true });
  await capital.fill("");
  await save.click();
  await expect(page.locator(".automation-action-notice")).toContainText("资金必须");
  expect(fixture.requests.filter((r) => r.method === "PATCH")).toHaveLength(0);
  await capital.fill("12.75");
  await page.getByLabel("入场冷却 (秒)", { exact: true }).fill("1");
  fixture.holdWrite();
  await save.click();
  await expect(capital).toBeDisabled();
  await expect(page.getByRole("button", { name: "正在更新…", exact: true })).toBeDisabled();
  fixture.tick();
  fixture.failWrite();
  fixture.releaseWrite();
  await expect(page.locator(".automation-action-notice")).toContainText("save rejected");
  await expect(capital).toHaveValue("12.75");
  await expect(save).toBeEnabled();
  fixture.failWrite(false);
  await save.click();
  await expect(page.locator(".automation-action-notice")).toHaveText("自动化配置已保存");
  await expect(page.locator(".automation-entry-config .automation-draft-state")).toContainText("与已保存配置一致");
  await expect(page.locator(".automation-guard-summary")).toContainText("$12.75");
  expect(fixture.requests.filter((r) => r.method === "PATCH").map((r) => r.body.capitalUsd)).toEqual([12.75, 12.75]);
  expect(fixture.requests.filter((r) => r.method === "PATCH").map((r) => r.body.cooldownSecs)).toEqual([1, 1]);
  expect(fixture.errors).toEqual([]);
});

