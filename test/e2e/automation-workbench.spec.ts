test("automation receipts follow leg finality and exact linked closes without submitting orders", async ({ page }, info) => {
  const fixture = await setup(page);
  const status = runtime();
  status.config.enabled = true;
  status.state = "submitting";
  status.activeRunCount = 1;
  status.lastDecision = { id: "decision-receipt", kind: "submitted", symbol: "SOL", reason: "fixture: submitted",
    executionRunId: "fixture-run-0", occurredAtMs: NOW };
  status.recentDecisions = [status.lastDecision];
  const evidence = receipt();
  fixture.setReceipt(evidence);
  fixture.setStatus(status);
  await page.goto(`${WEB}/#automation`);
  await page.getByRole("button", { name: "查看回执", exact: true }).click();
  const panel = page.getByRole("region", { name: "自动化运行回执", exact: true });
  await expect(panel).toContainText("ACK，非成交终态");
  await expect(panel).toContainText("尚无匹配的平仓回执");
  const emitRun = () => fixture.execution({ event: "execution_run_updated", executionRun: evidence.run, timestampMs: ++evidence.run.updatedAtMs });
  Object.assign(evidence.run.longLeg, { state: "filled", filledQuantity: 1, filledNotionalUsd: 10,
    finalitySource: "private_ws", confirmedFilledAtMs: NOW });
  emitRun();
  await expect(panel.locator(".automation-receipt-leg").first()).toContainText("已成交");
  await page.getByRole("tab", { name: "当前闭环", exact: true }).click();
  await expect(page.locator(".automation-flow-panel li").nth(4)).toContainText("等待双腿成交证据");
  evidence.run.state = "unwind_required";
  emitRun();
  await expect(page.locator(".automation-flow-panel li").nth(4)).toHaveAttribute("data-state", "blocked");
  Object.assign(evidence.run.shortLeg, { state: "filled", filledQuantity: 1, filledNotionalUsd: 10,
    finalitySource: "private_ws", confirmedFilledAtMs: NOW });
  evidence.run.state = "hedged";
  emitRun();
  await expect(page.locator(".automation-flow-panel li").nth(4)).toHaveAttribute("data-state", "complete");
  const close = closeReceipt(evidence.run);
  const wrongClose = structuredClone(close);
  wrongClose.id = "wrong-ticket";
  wrongClose.legs.forEach((leg) => { leg.pairEvidence.ticketId = "other-ticket"; });
  const emitClose = (value: typeof close) => fixture.execution({ event: "close_run_updated", closeRun: value, timestampMs: ++value.updatedAtMs });
  emitClose(wrongClose);
  emitClose(close);
  await expect(page.locator(".automation-flow-panel li").nth(5)).toHaveAttribute("data-state", "warning");
  await page.getByRole("tab", { name: "运行回执", exact: true }).click();
  await expect(panel.locator(".automation-close-receipt")).toHaveCount(1);
  const details = panel.locator(".automation-close-receipt");
  await details.locator("summary").click();
  await details.locator("summary").focus();
  close.status = "failed";
  emitClose(close);
  await expect(details).toContainText("平仓失败");
  close.status = "succeeded";
  close.message = "fixture: fills confirmed; costs still unknown";
  close.legs.forEach((leg) => Object.assign(leg, { status: "filled", finalitySource: "private_ws", confirmedFilledAtMs: NOW }));
  close.legs[1].quantity = 0.5;
  emitClose(close);
  await page.getByRole("tab", { name: "当前闭环", exact: true }).click();
  await expect(page.locator(".automation-flow-panel li").nth(5)).toHaveAttribute("data-state", "warning");
  await page.getByRole("tab", { name: "运行回执", exact: true }).click();
  await details.locator("summary").click();
  await details.locator("summary").focus();
  close.legs[1].quantity = 1;
  emitClose(close);
  await expect(details).toHaveAttribute("open", "");
  await expect(details.locator("summary")).toBeFocused();
  await expect(details).toContainText("本次平仓已成交");
  await expect(details).toContainText("退出费用尚未核清");
  await page.screenshot({ path: info.outputPath("automation-receipts-desktop.png") });
  await page.setViewportSize({ width: 390, height: 900 });
  await panel.scrollIntoViewIfNeeded();
  expect(await page.locator(".automation-page").evaluate((el) => el.scrollWidth <= el.clientWidth + 1)).toBeTruthy();
  await panel.screenshot({ path: info.outputPath("automation-receipts-mobile.png") });
  await page.getByRole("tab", { name: "当前闭环", exact: true }).click();
  await expect(page.locator(".automation-flow-panel li").nth(5)).toHaveAttribute("data-state", "complete");
  await expect(page.locator(".automation-flow-panel li").nth(6)).toContainText("净收益待核算");
  expect(fixture.requests.every((request) => request.method === "GET")).toBeTruthy();
  expect(fixture.writes).toEqual([]);
  expect(fixture.errors).toEqual([]);
});

test("automation receipts fence old reads run switches and failed refreshes", async ({ page }) => {
  const fixture = await setup(page);
  const status = runtime();
  status.recentDecisions = ["fixture-run-0", "fixture-run-1"].map((id) => ({ id, kind: "submitted", symbol: "SOL",
    reason: "fixture: submitted", executionRunId: id, occurredAtMs: NOW }));
  status.lastDecision = status.recentDecisions[0];
  const first = receipt();
  const second = receipt("fixture-run-1");
  second.run.netExposureUsd = 7;
  fixture.setReceipt(first);
  fixture.setReceipt(second);
  fixture.setStatus(status);
  await page.goto(`${WEB}/#automation`);
  await page.getByRole("tab", { name: "运行回执", exact: true }).click();
  const panel = page.getByRole("region", { name: "自动化运行回执", exact: true });
  await expect(panel.locator(".automation-receipt-summary")).toContainText("fixture-run-0");
  fixture.holdReceipt("fixture-run-0");
  await panel.getByRole("button", { name: "刷新回执", exact: true }).click();
  await expect(panel.getByRole("button", { name: "读取中…", exact: true })).toBeDisabled();
  first.run.netExposureUsd = 3;
  fixture.execution({ event: "execution_run_updated", executionRun: first.run, timestampMs: NOW + 1 });
  await expect(panel.locator(".automation-receipt-summary > div").nth(2)).toContainText("3");
  fixture.releaseReceipt();
  await expect(panel.getByRole("button", { name: "刷新回执", exact: true })).toBeEnabled();
  await expect(panel.locator(".automation-receipt-summary > div").nth(2)).toContainText("3");
  fixture.holdReceipt("fixture-run-0");
  await panel.getByRole("button", { name: "刷新回执", exact: true }).click();
  await expect(panel.getByRole("button", { name: "读取中…", exact: true })).toBeDisabled();
  await page.getByLabel("选择自动化运行记录").selectOption("fixture-run-1");
  await expect(panel.locator(".automation-receipt-summary")).toContainText("fixture-run-1");
  fixture.releaseReceipt();
  await expect(panel.locator(".automation-receipt-summary > div").nth(2)).toContainText("7");
  fixture.failReceipt();
  await panel.getByRole("button", { name: "刷新回执", exact: true }).click();
  await expect(panel.getByRole("status")).toContainText("回执待确认，保留上次记录");
  await expect(panel.locator(".automation-receipt-summary")).toContainText("fixture-run-1");
  fixture.failReceipt(false);
  await panel.getByRole("button", { name: "刷新回执", exact: true }).click();
  await expect(panel.getByRole("status")).toContainText("本地执行账本");
  fixture.holdReceipt("fixture-run-1");
  await panel.getByRole("button", { name: "刷新回执", exact: true }).click();
  await expect(panel.getByRole("button", { name: "读取中…", exact: true })).toBeDisabled();
  await page.goto(`${WEB}/#futures`);
  fixture.releaseReceipt();
  expect(fixture.errors).toEqual([]);
});
